#!/usr/bin/env python3
"""Render original MIT UI symbols to small, static LVGL alpha masks."""
from pathlib import Path
from PIL import Image, ImageDraw
ROOT = Path(__file__).resolve().parents[1]
SCALE=8

def mask(size, draw):
    im=Image.new('L',(size*SCALE,size*SCALE))
    d=ImageDraw.Draw(im)
    draw(d,SCALE)
    return list(im.resize((size,size),Image.Resampling.LANCZOS).get_flattened_data())

def wave(d,s):
    for x,h in [(2,8),(7,16),(12,26),(17,16),(22,8)]:
        y=(28-h)/2
        d.rounded_rectangle((x*s,y*s,(x+3)*s,(y+h)*s),radius=1.5*s,fill=255)

def timer(d,s):
    d.ellipse((2*s,4*s,14*s,16*s),outline=255,width=round(1.5*s))
    d.rounded_rectangle((6*s,0,10*s,2*s),radius=s/2,fill=255)
    d.line((8*s,2*s,8*s,4*s),fill=255,width=s)
    d.line((8*s,7*s,8*s,10*s,11*s,10*s),fill=255,width=round(1.5*s))

def exit_app(d,s):
    d.line((6*s,2*s,2*s,2*s,2*s,14*s,6*s,14*s),fill=255,width=round(1.5*s))
    d.line((5*s,8*s,14*s,8*s),fill=255,width=round(1.5*s))
    d.line((10*s,4*s,14*s,8*s,10*s,12*s),fill=255,width=round(1.5*s))

for name,size,draw in [('voice_wave',28,wave),('timer',16,timer),('exit',16,exit_app)]:
    pixels=mask(size,draw)
    text=[f'/* Original project artwork (MIT), generated by tools/render_ui_icons.py. */',
          f'static const uint8_t {name}_pixels[{size*size}]={{']
    text.extend('    '+','.join(map(str,pixels[i:i+size]))+',' for i in range(0,len(pixels),size))
    symbol=name if name=='voice_wave' else name+'_symbol'
    text+=['};',f'static const lv_image_dsc_t {symbol}_image={{.header={{.magic=LV_IMAGE_HEADER_MAGIC,.cf=LV_COLOR_FORMAT_A8,.w={size},.h={size},.stride={size}}},.data_size={size*size},.data={name}_pixels}};']
    filename='ui_wave.inc' if name=='voice_wave' else f'ui_{name}.inc'
    (ROOT/'main/vibe'/filename).write_text('\n'.join(text)+'\n')
